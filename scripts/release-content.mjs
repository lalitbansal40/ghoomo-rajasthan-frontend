import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve, relative } from 'node:path';
import { launchGate, sourceApprovals } from './phase7/launch-gate.mjs';

const root = fileURLToPath(new URL('..', import.meta.url));
const output = 'src/lib/release-content.ts';
const excluded = new Set([output, 'src/lib/release-manifest.ts']);
async function files(dir) {
  const result = [];
  for (const entry of await readdir(resolve(root, dir), { withFileTypes: true })) {
    const path = `${dir}/${entry.name}`;
    if (excluded.has(path) || /\.test\.[cm]?[jt]sx?$/.test(path)) continue;
    if (entry.isDirectory()) result.push(...await files(path));
    else if (entry.isFile()) result.push(path);
  }
  return result;
}
// One deliberately conservative static-content set: source/assets/lock/config changes require
// renewed release review. Never hash env files, generated approvals or this generated output.
const paths = [...await files('src'), ...await files('public'), 'package.json', 'package-lock.json', 'next.config.ts'].sort();
const hash = createHash('sha256');
for (const path of paths) {
  hash.update(path + '\0'); hash.update(createHash('sha256').update(await readFile(resolve(root, path))).digest());
}
const revision = hash.digest('hex');
const content = `// Generated by scripts/release-content.mjs. No approvals are created here.\nexport const STATIC_CONTENT_REVISION = '${revision}';\n`;
if (process.argv.includes('--check')) {
  if (await readFile(resolve(root, output), 'utf8').catch(() => '') !== content) throw Error('STALE_RELEASE_CONTENT: run node scripts/release-content.mjs');
} else if (await readFile(resolve(root, output), 'utf8').catch(() => '') !== content) {
  await writeFile(resolve(root, output), content);
}
const flag = (await readFile(resolve(root, 'src/lib/site.ts'), 'utf8')).match(/^export const SITE_LAUNCHED = (true|false);$/m);
if (!flag) throw Error('Explicit audited SITE_LAUNCHED boolean required');
const gate = launchGate({ launched: flag[1] === 'true', approvals: await sourceApprovals(await readFile(resolve(root, 'src/lib/release-manifest.ts'), 'utf8')), revision });
console.log(JSON.stringify({ revision, files: paths.length, output: relative(root, resolve(root, output)), mode: process.argv.includes('--check') ? 'check' : 'generate', gate }));
