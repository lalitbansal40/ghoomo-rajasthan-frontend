"""Writes src/components/motifs/paths.generated.ts — the shapes of the logo, for the site's motifs
(camel, fort, car, the jharokha arch). One drawing for the logo and the site, so they always match.
    .venv/bin/python motifs.py
"""
import os, sys, json
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import art
from car import car

ROZHA = os.path.join(HERE, 'fonts/RozhaOne-Regular.ttf')
out = {
    # the camel, origin at its feet (60 x 47 units)
    'CAMEL_D': art.CAMEL,
    'SADDLE_D': art.SADDLE,
    # the fort on its rock, drawn in currentColor (windows in the sun colour)
    'FORT_SVG': art.fort('currentColor'),
    # the white car, Ghoomo Rajasthan on its side; wheels in spinnable groups
    'CAR_SVG': car(ROZHA, animated=True),
    # the jharokha arch (200 x 240): outer band, inner window, the cusps
    'ARCH_OUTER_D': art.OUTER,
    'ARCH_INNER_D': art.INNER,
    'ARCH_CUSPS_SVG': art.cusps(),
}
lines = ['// GENERATED by scripts/brand/motifs.py from the logo drawing (art.py, car.py) — do not edit.',
        ]
for k, v in out.items():
    lines.append(f'export const {k} = {json.dumps(v)};')
dest = os.path.join(HERE, '../../src/components/motifs/paths.generated.ts')
os.makedirs(os.path.dirname(dest), exist_ok=True)
open(dest, 'w').write('\n'.join(lines) + '\n')
print('wrote', os.path.relpath(dest, HERE), os.path.getsize(dest), 'bytes')
