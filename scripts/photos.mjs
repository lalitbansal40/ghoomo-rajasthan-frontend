/**
 * Photos from Wikimedia Commons, under a free licence, sized for the web, with their credits.
 *   node scripts/photos.mjs
 *
 * For each entry in scripts/photo-list.json: the licence, author and description are read
 * from the Commons API (never assumed); anything not CC0 / public domain / CC BY / CC BY-SA is
 * refused; the original is downloaded once (scripts/.originals, not committed), then
 *   public/img/<key>-1280.webp   16:9, 1280 wide — heroes and banners
 *   public/img/<key>-640.webp    4:3, 640 wide — cards
 * and src/content/photos.ts is written with what /photo-credits shows.
 */
import sharp from 'sharp';
import { existsSync, mkdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const UA = { 'User-Agent': 'GhoomoRajasthanSite/0.1 (https://ghoomorajasthan.com) photo-credits' };
const list = JSON.parse(readFileSync(join(root, 'scripts/photo-list.json'), 'utf8'));
const ORIG = join(root, 'scripts/.originals');
mkdirSync(ORIG, { recursive: true });
mkdirSync(join(root, 'public/img'), { recursive: true });

const ALLOWED = [
  [/^CC0/i, 'CC0'],
  [/^(Public domain|PD)/i, 'Public domain'],
  [/^CC BY-SA 2\.0$/i, 'CC BY-SA 2.0'],
  [/^CC BY-SA 3\.0$/i, 'CC BY-SA 3.0'],
  [/^CC BY-SA 4\.0$/i, 'CC BY-SA 4.0'],
  [/^CC BY 2\.0$/i, 'CC BY 2.0'],
  [/^CC BY 3\.0$/i, 'CC BY 3.0'],
  [/^CC BY 4\.0$/i, 'CC BY 4.0'],
];
const strip = (h) =>
  String(h ?? '')
    .replace(/<[^>]+>/g, ' ')
    .replace(/&amp;/g, '&')
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/\s+/g, ' ')
    .trim();

const out = [];
for (const p of list) {
  const api = 'https://commons.wikimedia.org/w/api.php?' + new URLSearchParams({
    action: 'query', format: 'json', titles: `File:${p.title}`, prop: 'imageinfo', iiprop: 'url|size|extmetadata',
  });
  const page = Object.values((await (await fetch(api, { headers: UA })).json()).query.pages)[0];
  const ii = page.imageinfo?.[0];
  if (!ii) throw new Error(`not on Commons: ${p.title}`);
  const m = ii.extmetadata ?? {};
  const short = strip(m.LicenseShortName?.value);
  const licence = ALLOWED.find(([re]) => re.test(short))?.[1];
  if (!licence) throw new Error(`licence not allowed (${short}): ${p.title}`);
  if (m.Restrictions?.value) console.warn(`  note restrictions on ${p.key}: ${strip(m.Restrictions.value)}`);
  // The author as the file page names them; `credit` in the list only tidies how it reads
  // ("Yann (talk)" → "Yann") — never a different person.
  const credit = p.credit ?? (strip(m.Artist?.value) || strip(m.Credit?.value) || 'Unknown');

  const orig = join(ORIG, `${p.key}${ii.url.match(/\.\w+$/)?.[0] ?? '.jpg'}`);
  if (!existsSync(orig)) {
    // A large thumbnail is plenty for 1280 px and far lighter than a 6000 px original.
    const thumb = 'https://commons.wikimedia.org/w/api.php?' + new URLSearchParams({
      action: 'query', format: 'json', titles: `File:${p.title}`, prop: 'imageinfo', iiprop: 'url', iiurlwidth: '2400',
    });
    const t = Object.values((await (await fetch(thumb, { headers: UA })).json()).query.pages)[0].imageinfo[0];
    const res = await fetch(t.thumburl ?? t.url, { headers: UA });
    if (!res.ok) throw new Error(`download ${res.status}: ${p.title}`);
    writeFileSync(orig, Buffer.from(await res.arrayBuffer()));
  }
  const big = join(root, `public/img/${p.key}-1280.webp`);
  const card = join(root, `public/img/${p.key}-640.webp`);
  await sharp(orig).rotate().resize(1280, 720, { fit: 'cover', position: p.position ?? 'attention' }).webp({ quality: p.quality ?? 75 }).toFile(big);
  await sharp(orig).rotate().resize(640, 480, { fit: 'cover', position: p.position ?? 'attention' }).webp({ quality: p.quality ?? 75 }).toFile(card);
  const kb = (f) => Math.round(statSync(f).size / 1024);
  console.log(`${p.key}: ${licence} · ${credit.slice(0, 40)} · ${kb(big)} KB / ${kb(card)} KB`);
  out.push({
    key: p.key,
    alt: p.alt,
    big: `/img/${p.key}-1280.webp`,
    card: `/img/${p.key}-640.webp`,
    credit,
    licence,
    sourceUrl: ii.descriptionurl,
    changes: 'Cropped to 16:9 and 4:3, resized, converted to WebP',
  });
}

const ts = `// GENERATED by scripts/photos.mjs from scripts/photo-list.json — do not edit by hand.
/**
 * Every photograph on the site: free-licence, from Wikimedia Commons, its licence and author
 * read from the Commons API when the file was made. CC BY and CC BY-SA ask for the author,
 * the licence, the source and the changes to be named — /photo-credits does that for all of
 * them. Never a photograph from a search engine or another site.
 */
export type Licence =
  | 'CC0'
  | 'Public domain'
  | 'CC BY 2.0'
  | 'CC BY 3.0'
  | 'CC BY 4.0'
  | 'CC BY-SA 2.0'
  | 'CC BY-SA 3.0'
  | 'CC BY-SA 4.0';

export interface Photo {
  key: string;
  alt: string;
  /** 16:9, 1280 wide. */
  big: string;
  /** 4:3, 640 wide. */
  card: string;
  credit: string;
  licence: Licence;
  sourceUrl: string;
  changes: string;
}

export const LICENCE_URL: Record<Licence, string | null> = {
  CC0: 'https://creativecommons.org/publicdomain/zero/1.0/',
  'Public domain': null,
  'CC BY 2.0': 'https://creativecommons.org/licenses/by/2.0/',
  'CC BY 3.0': 'https://creativecommons.org/licenses/by/3.0/',
  'CC BY 4.0': 'https://creativecommons.org/licenses/by/4.0/',
  'CC BY-SA 2.0': 'https://creativecommons.org/licenses/by-sa/2.0/',
  'CC BY-SA 3.0': 'https://creativecommons.org/licenses/by-sa/3.0/',
  'CC BY-SA 4.0': 'https://creativecommons.org/licenses/by-sa/4.0/',
};

export const PHOTOS: Photo[] = ${JSON.stringify(out, null, 2)};

export const photo = (key: string) => PHOTOS.find((p) => p.key === key) ?? null;
`;
writeFileSync(join(root, 'src/content/photos.ts'), ts);
console.log(`${out.length} photos → public/img, src/content/photos.ts`);
