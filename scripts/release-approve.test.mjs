import { test } from 'node:test';
import assert from 'node:assert/strict';
import { buildApprovals, manifestSource, REFUSED } from './release-approve.mjs';
import { launchGate } from './phase7/launch-gate.mjs';
import * as contract from '../src/lib/release-contract.ts';
import * as policy from '../src/lib/indexing-policy.ts';

const revA = 'a'.repeat(64);
const revB = 'b'.repeat(64);
const now = Date.parse('2026-10-21T00:00:00Z');
const list = (paths) => ({
  approvedBy: 'Lalit Bansal (owner)',
  approvedAt: '2026-10-20T00:00:00Z',
  evidence: 'docs/release/PHASE1_APPROVAL.md',
  paths,
});
const ctx = (paths, staticRevision = revA) => ({
  list: list(paths),
  staticRevision,
  sampleRevision: 1,
  samplePackages: new Set(['royal-rajasthan-circuit']),
  heldPaths: new Set(['/cab/ajmer-to-pushkar']),
  contract,
  policy,
});

test('every listed path gets an English and a Hindi approval at the right revision', () => {
  const a = buildApprovals(ctx(['/', '/cab', '/destinations/jaipur', '/packages/royal-rajasthan-circuit']));
  assert.equal(a.length, 8);
  assert.deepEqual(a.map((x) => x.path), ['/', '/hi', '/cab', '/hi/cab', '/destinations/jaipur', '/hi/destinations/jaipur', '/packages/royal-rajasthan-circuit', '/hi/packages/royal-rajasthan-circuit']);
  for (const x of a.slice(0, 6)) assert.equal(x.revision, revA);
  for (const x of a.slice(6)) assert.equal(x.revision, 1, 'a sample tour carries the fixed sample revision');
  for (const x of a) {
    assert.equal(x.evidence, 'docs/release/PHASE1_APPROVAL.md');
    assert.equal(x.approvedBy, 'Lalit Bansal (owner)');
  }
});

test('a wrong list can never index what must stay out', () => {
  const refuse = (paths, code) => assert.throws(() => buildApprovals(ctx(paths)), new RegExp(code));
  refuse(['/booking'], 'PRIVATE');
  refuse(['/my-bookings'], 'PRIVATE');
  refuse(['/photo-credits'], 'UTILITY');
  refuse(['/styleguide'], 'UTILITY');
  refuse(['/cab/ajmer-to-pushkar'], 'HELD');
  for (const p of REFUSED) refuse([p], 'PRIVATE|REFUSED|UTILITY');
  refuse(['/hi/cab'], 'LOCALE');
  refuse(['/hi'], 'LOCALE');
  refuse(['/cab', '/cab'], 'DUPLICATE');
  refuse(['/packages/not-a-sample'], 'DYNAMIC');
  refuse(['/tours/some-tour'], 'DYNAMIC');
  refuse(['/Cab'], 'PRIVATE');
  refuse([], 'paths');
});

test('a list without a named approver, a date or evidence is refused', () => {
  const base = ctx(['/']);
  assert.throws(() => buildApprovals({ ...base, list: { ...base.list, approvedBy: '' } }), /approvedBy/);
  assert.throws(() => buildApprovals({ ...base, list: { ...base.list, approvedAt: '20 Oct' } }), /approvedAt/);
  assert.throws(() => buildApprovals({ ...base, list: { ...base.list, evidence: '../secret' } }), /evidence/);
  assert.throws(() => buildApprovals({ ...base, staticRevision: 'nope' }), /STATIC_REVISION/);
});

test('the unchanged gate accepts the generated approvals once launched, and still refuses none', () => {
  const approvals = buildApprovals(ctx(['/', '/cab', '/packages/royal-rajasthan-circuit']));
  assert.equal(launchGate({ launched: true, approvals, revision: revA, now }).approvals, 6);
  assert.throws(() => launchGate({ launched: true, approvals: [], revision: revA, now }), /RELEASE_NOT_REVIEWED/);
});

test('a code change (new revision) keeps every approval and the build passing — Phase 1 risks A and B', () => {
  // Hand-written approvals at the old revision fail the gate once the code changes...
  const stale = buildApprovals(ctx(['/', '/cab'], revA));
  assert.throws(() => launchGate({ launched: true, approvals: stale, revision: revB, now }));
  // ...regenerated from the same list at the new revision, they pass.
  const fresh = buildApprovals(ctx(['/', '/cab'], revB));
  assert.equal(launchGate({ launched: true, approvals: fresh, revision: revB, now }).approvals, 4);
});

test('the manifest file is deterministic and says it is generated', () => {
  const approvals = buildApprovals(ctx(['/']));
  const src = manifestSource(approvals);
  assert.equal(src, manifestSource(approvals));
  assert.match(src, /^\/\/ Generated by scripts\/release-approve\.mjs/);
  assert.match(src, /export const RELEASE_APPROVALS: readonly ReleaseApproval\[\] = \[/);
});
