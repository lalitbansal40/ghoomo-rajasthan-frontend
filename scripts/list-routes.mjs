/**
 * Every route the backend publishes (owner, 16 Oct 2026: all of Hello My Cab's routes on
 * Ghoomo too), with its distance and whether it touches Rajasthan.
 *   npm run routes:sync      → docs/routes.csv + src/content/routes/hmc.generated.ts
 * and says which routes the backend added or dropped since the last run. Reads only the
 * public API — no keys.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const API = process.env.NEXT_PUBLIC_API_BASE_URL ?? 'https://api.hellomycabs.com/api/v1';
const get = async (p) => {
  const r = await fetch(`${API}/public${p}`);
  const b = await r.json();
  if (!b.ok) throw new Error(`${p}: ${b.error?.message ?? r.status}`);
  return b.data;
};

const [{ cityList }, { routes }] = await Promise.all([get('/cities'), get('/routes')]);
const state = Object.fromEntries(cityList.map((c) => [c.name, c.state]));
const label = Object.fromEntries(cityList.map((c) => [c.name, c.label]));
const inRaj = (k) => (state[k] ?? '').toLowerCase() === 'rajasthan';

const rows = routes
  .map((r) => ({
    pickup: r.pickup,
    drop: r.drop,
    from: label[r.pickup] ?? r.pickup,
    to: label[r.drop] ?? r.drop,
    km: r.distanceKm ?? '',
    rajasthan: inRaj(r.pickup) && inRaj(r.drop) ? 'both' : inRaj(r.pickup) || inRaj(r.drop) ? 'one end' : 'no',
    fixed: r.fixed ? 'yes' : 'no',
  }))
  .sort((a, b) => {
    const rank = { both: 0, 'one end': 1, no: 2 };
    return rank[a.rajasthan] - rank[b.rajasthan] || a.from.localeCompare(b.from) || a.to.localeCompare(b.to);
  });

const esc = (v) => (/[",\n]/.test(String(v)) ? `"${String(v).replace(/"/g, '""')}"` : String(v));
const head = ['pickup_key', 'drop_key', 'from', 'to', 'km', 'rajasthan', 'fixed_fare', 'ghoomo_text_written'];
const csv = [head.join(','), ...rows.map((r) => [r.pickup, r.drop, r.from, r.to, r.km, r.rajasthan, r.fixed, 'no'].map(esc).join(','))].join('\n');
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
writeFileSync(join(root, 'docs/routes.csv'), csv + '\n');

// The page list — what the site builds a /cab/… page for.
const genPath = join(root, 'src/content/routes/hmc.generated.ts');
const before = existsSync(genPath)
  ? new Set([...readFileSync(genPath, 'utf8').matchAll(/pickup: '(\w+)', drop: '(\w+)'/g)].map((m) => `${m[1]}>${m[2]}`))
  : null;
const RAJ = { both: 'both', 'one end': 'oneEnd', no: 'none' };
const gen = [
  '// GENERATED by scripts/list-routes.mjs (npm run routes:sync) — do not edit by hand.',
  '/** Every route the Hello My Cab backend publishes (/public/routes), as of the last sync. */',
  'export const HMC_ROUTES = [',
  ...rows.map(
    (r) => `  { pickup: '${r.pickup}', drop: '${r.drop}', rajasthan: '${RAJ[r.rajasthan]}', fixed: ${r.fixed === 'yes'} },`,
  ),
  '] as const;',
  '',
].join('\n');
writeFileSync(genPath, gen);
if (before) {
  const now = new Set(rows.map((r) => `${r.pickup}>${r.drop}`));
  const added = [...now].filter((k) => !before.has(k));
  const dropped = [...before].filter((k) => !now.has(k));
  console.log(added.length || dropped.length ? `added: ${added.join(', ') || '—'} · dropped: ${dropped.join(', ') || '—'}` : 'no change since the last sync');
}
const count = (k) => rows.filter((r) => r.rajasthan === k).length;
console.log(`${rows.length} routes → docs/routes.csv (Rajasthan both ends: ${count('both')}, one end: ${count('one end')}, outside: ${count('no')})`);
