/**
 * src/design/tokens.json → src/design/tokens.css (Tailwind 4 @theme + the type utilities).
 *   npm run tokens
 * The JSON is the one source; never edit the CSS by hand.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const t = JSON.parse(readFileSync(join(root, 'src/design/tokens.json'), 'utf8'));
const L = [];
L.push('/* GENERATED by scripts/tokens.mjs from src/design/tokens.json — edit the JSON, then `npm run tokens`. */');
L.push('@theme {');
for (const [k, v] of Object.entries(t.color)) L.push(`  --color-${k}: ${v};`);
for (const [k, v] of Object.entries(t.alias)) if (!k.startsWith('$')) L.push(`  --color-${k}: var(--color-${v});`);
for (const [k, v] of Object.entries(t.radius)) L.push(`  --radius-${k}: ${v};`);
for (const [k, v] of Object.entries(t.shadow)) L.push(`  --shadow-${k}: ${v};`);
// Every motion token: easings and durations, the desert scene's included (Phase 4).
for (const [k, v] of Object.entries(t.motion)) if (!k.startsWith('$')) L.push(`  --${k}: ${v};`);
// 'Rupee' first: the ₹ sign from the phone's own font (globals.css), so ₹ alone does not pull
// Mukta's latin-ext files onto every page.
L.push("  --font-sans: 'Rupee', var(--font-mukta), ui-sans-serif, system-ui, sans-serif;");
L.push("  --font-display: 'Rupee', var(--font-display-face), var(--font-mukta), serif;");
L.push(`  --container-site: ${t.layout.container};`);
L.push('}');
L.push('');
// Web roles are scoped independently of fixed brand primitives consumed by Flutter/artwork.
L.push('@theme inline {');
for (const key of Object.keys(t.webTheme.light)) L.push(`  --color-${key}: var(--gr-${key});`);
L.push('}');
for (const [theme, roles] of Object.entries(t.webTheme)) {
  L.push(theme === 'light' ? ':root, [data-theme="light"] {' : '[data-theme="dark"] {');
  L.push(`  color-scheme: ${theme};`);
  for (const [key, value] of Object.entries(roles)) L.push(`  --gr-${key}: ${value};`);
  if (theme === 'dark') {
    L.push('  --shadow-card: 0 1px 2px rgb(0 0 0 / .2), 0 4px 14px rgb(0 0 0 / .25);');
    L.push('  --shadow-raised: 0 2px 4px rgb(0 0 0 / .25), 0 12px 32px rgb(0 0 0 / .4);');
  } else {
    for (const [key, value] of Object.entries(t.shadow)) L.push(`  --shadow-${key}: ${value};`);
  }
  L.push('}');
}
L.push('@media print { :root {');
for (const [key, value] of Object.entries(t.webTheme.light)) L.push(`  --gr-${key}: ${value} !important;`);
L.push('  color-scheme: light; } }');
L.push('');
L.push('/* The type scale — one class per step; Hindi gets a little more line-height for its matras. */');
L.push('@layer components {');
for (const [k, v] of Object.entries(t.type)) {
  const fam = v.family === 'display' ? 'var(--font-display)' : 'var(--font-sans)';
  const extra = k === 'price' ? ' font-variant-numeric: tabular-nums;' : '';
  L.push(`  .text-${k} { font-family: ${fam}; font-size: ${v.size}; line-height: ${v.line}; font-weight: ${v.weight};${extra} }`);
  const hiLine = (Number(v.line) + (v.family === 'display' ? 0.15 : 0.1)).toFixed(2).replace(/0$/, '');
  L.push(`  :lang(hi) .text-${k}, .text-${k}:lang(hi) { line-height: ${hiLine}; }`);
}
L.push('}');
writeFileSync(join(root, 'src/design/tokens.css'), L.join('\n') + '\n');
console.log('src/design/tokens.css written');
